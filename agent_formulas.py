"""
agent_formulas.py — все экономические формулы агентов в одном месте.

Здесь нет ни классов, ни состояния, ни обращений к биржам — только чистые
функции и константы, описывающие поведение агентов. Симуляция
(agent_simulation.py) лишь подставляет в них наблюдаемые величины.

Роли агентов
------------
    T1, T2 — трансляторы (переводчики): привязаны к лимитной бирже 1 / 2,
             переносят её цену и ликвидность на непрерывную биржу (CE)
             и хеджируют накопленный инвентарь об домашний стакан.
    AX, AY — арбитражёры: торгуют только на CE один актив против его
             двойника с другой площадки (X1/X2 или Y1/Y2).

Гиперпараметры (свои у каждого агента, эволюция отбирает лучших)
----------------------------------------------------------------
    h_m — агрессивность: чем МЕНЬШЕ h_m, тем больше lambda (объём реакции
          на расхождение цены). Нейтральное значение 1.
    h_R — (только трансляторы) чувствительность к риску позиции: чем БОЛЬШЕ
          h_R, тем сильнее сдвигается котировка от инвентаря и тем раньше
          и глубже агент хеджируется. Нейтральное значение 1.

Единицы измерения
-----------------
    X1        — базовый актив: единица счёта CE (P_X1 = 1), в нём выражены
                капитал, PnL, стоимость позиций и lambda.
    lambda    — [X1 / тик]: нотионал за тик на единицу лог-расхождения f.
    z         — курс двух активов (для двуногого портфеля +1/-1 это обычная
                цена: у T1 — цена Y1 в X1, у арбитражёров — отношение
                двойников, безразличие при 1).
    q_value   — стоимость позиции по торгуемой ноге, [X1] (штуки * мид).
    sigma2    — EWMA-дисперсия лог-приростов цены за тик, безразмерна.
    g         — риск-коэффициент, [1/X1]; g * q_value безразмерно.
    cost      — относительная потеря на единицу нотионала при хедже
                (полспреда), безразмерна.
"""

