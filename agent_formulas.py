# --------------------------------------------------------------------------- #
# Капитал и доля в семействе
# --------------------------------------------------------------------------- #

def capital(pnl: float, c0: float) -> float:
    """Капитал агента: стартовый (виртуальный) капитал плюс заработанное.

        C = C0 + PnL                                    [X1]

    C0 на баланс не кладётся — он живёт только в формулах доли и риска;
    прибыль остаётся ровно стоимостью реального портфеля (старт с нуля).
    """
    return c0 + pnl


def share(capital_i: float, family_capitals: list) -> float:
    """Доля агента в торговой мощности семейства.

        share_i = max(C_i, 0) / sum_семейство max(C_j, 0)

    Банкрот (C <= 0) получает долю 0 и перестаёт торговать ещё до
    эволюционной деактивации. Суммирование — только по живым агентам
    семейства, поэтому доля умерших перетекает живым.
    """
    total = sum(max(c, 0.0) for c in family_capitals)
    if total <= 0.0:
        return 0.0
    return max(capital_i, 0.0) / total


# --------------------------------------------------------------------------- #
# Торговая мощность (lambda заявки на CE)
# --------------------------------------------------------------------------- #

def book_quality(depth: float, mid: float, spread, tick_size: float) -> float:
    """Качество домашнего стакана H — сколько стоимости лежит у мида,
    со штрафом за широкий спред.

        H = depth * mid * tick_size / max(spread, tick_size)      [X1]

    depth — суммарный объём обеих сторон в полосе +-depth_band от мида
    (depth_near_mid лимитной биржи), depth * mid — его нотионал.
    tick_size / spread — безразмерная "теснота" книги: спред в один тик
    даёт 1 (лучше некуда), широкий спред — меньше. Пустая сторона стакана
    (spread is None) трактуется как бесконечный спред: H = 0, семейство
    этот тик молчит.
    """
    if spread is None or depth <= 0.0 or mid <= 0.0:
        return 0.0
    return depth * mid * tick_size / max(spread, tick_size)


def lam_translator(kappa_t: float, H: float, share_i: float, h_m: float) -> float:
    """Агрессивность заявки транслятора.

        Lambda_семейства = kappa_T * H          суммарная мощность семейства
        lambda_i = Lambda * share_i / h_m       доля конкретного агента

    kappa_T [1/тик] — какую часть книжного нотионала семейство готово
    провернуть за тик на единицу лог-расхождения: при kappa_T = 0.1 и
    расхождении цены CE с мидом в 1% семейство целиком торгует
    0.1 * H * 0.01 = 0.1% книжного нотионала за тик. Мощность привязана
    к домашнему стакану, потому что всё наторгованное на CE транслятору
    рано или поздно хеджировать об эту книгу.

    Единицы: H (а значит и lambda) номинирована в КЭШЕ домашней площадки
    (X1 у первой биржи, X2 у второй), потому что mid выражен в нём.
    Заявка на CE должна нести lam_ccy = <кэш площадки>, чтобы биржа сама
    конвертировала lambda в единицу счёта X1 по цене прошлого шага.
    """
    return kappa_t * H * share_i / h_m


def lam_arb(kappa_a: float, capital_i: float, h_m: float) -> float:
    """Агрессивность заявки арбитражёра.

        lambda_i = kappa_A * max(C_i, 0) / h_m

    Арбитражёр не видит лимитных бирж, опереться ему не на что, кроме
    собственного капитала: богатство и есть его торговая мощность,
    эволюция действует на неё напрямую. kappa_A [1/тик] — какую часть
    своего капитала агент проворачивает за тик на единицу расхождения.
    """
    return kappa_a * max(capital_i, 0.0) / h_m


# --------------------------------------------------------------------------- #
# Риск и котировка (цена безразличия z)
# --------------------------------------------------------------------------- #

def risk_coefficient(h_r: float, gamma: float, sigma2: float,
                     capital_i: float, capital_floor: float) -> float:
    """Риск-коэффициент агента.

        g = h_R * gamma * sigma2 / max(C, capital_floor)          [1/X1]

    gamma — общее для всех неприятие риска (одна константа системы),
    sigma2 — дисперсия лог-приростов релевантной цены за тик,
    C — капитал: богатый агент спокойнее держит ту же позицию.
    capital_floor страхует от деления на ноль у банкрота: его g
    становится очень большим — "разорившийся ликвидируется".
    """
    return h_r * gamma * sigma2 / max(capital_i, capital_floor)


def shaded_quote(anchor: float, g: float, q_value: float,
                 clamp: float = 1.0) -> float:
    """Цена безразличия со сдвигом против собственной позиции (шейдинг).

        z = anchor * exp(-g * q_value)

    anchor — базовая оценка курса (мид домашней биржи у транслятора,
    1 у арбитражёра). Лонг (q > 0) опускает z ниже anchor — агент охотнее
    продаёт; шорт поднимает — охотнее откупает. Сила пружины
    пропорциональна отклонению и исчезает при q -> 0, поэтому механизм
    тянет позицию к нулю, а не "сливает актив". Внутри хедж-коридора
    сдвиг не превышает полспреда (см. hedge_excess_value).
    Экспонента гарантирует z > 0; |g*q| ограничен clamp на случай
    патологий (огромная позиция при копеечном капитале).
    """
    shift = min(max(g * q_value, -clamp), clamp)
    return anchor * math.exp(-shift)


# --------------------------------------------------------------------------- #
# Хедж транслятора об домашний стакан
# --------------------------------------------------------------------------- #

def hedge_cost(spread, mid: float, tick_size: float):
    """Относительная потеря на единицу нотионала при немедленном хедже.

        cost = 0.5 * spread / mid                       (безразмерна)

    Скидывать приходится не по миду, а по встречной стороне книги —
    теряется примерно полспреда. Комиссий нет. Спред ограничен снизу
    тиком (кроссированная книга не делает хедж бесплатным); при пустой
    стороне (spread is None) стоимость не определена — хедж невозможен,
    возвращается None.
    """
    if spread is None or mid <= 0.0:
        return None
    return 0.5 * max(spread, tick_size) / mid


def hedge_excess_value(g: float, q_value: float, cost: float) -> float:
    """Сколько стоимости позиции нужно скинуть (0 — хедж не нужен).

    Логика равенства предельных величин:
        держать невыгодно, когда   g * |q| > cost
            (риск последней единицы позиции превысил потерю на её сброс)
        скидываем излишек до точки равенства  |q*| = cost / g:
            excess = |q| - cost / g                     [X1]

    Констант нет: порог и цель следуют из сравнения риска и потери в одних
    единицах. Гистерезис встроен — сразу после хеджа риск равен потере, и
    повторный триггер не сработает, пока позиция снова не вырастет.
    Направление сброса определяет знак q (лонг продаём, шорт откупаем).
    """
    if g <= 0.0:
        return 0.0
    abs_q = abs(q_value)
    if g * abs_q <= cost:
        return 0.0
    return abs_q - cost / g


# --------------------------------------------------------------------------- #
# Калибровка
# --------------------------------------------------------------------------- #

def calibrate_gamma(cost: float, sigma2: float, q_max_fraction: float) -> float:
    """Подбор gamma из целевого хедж-порога.

    Порог хеджа |q*| = cost / g = cost * C / (gamma * sigma2). Требуем,
    чтобы при нейтральных h_R = 1 он равнялся заданной доле капитала
    (q_max_fraction * C); капитал сокращается, и остаётся

        gamma = cost / (sigma2 * q_max_fraction)

    cost и sigma2 берутся из состояния рынка после прогрева. Одна формула
    согласует и частоту хеджей, и масштаб шейдинга котировок.
    """
    return cost / (max(sigma2, 1e-12) * q_max_fraction)
